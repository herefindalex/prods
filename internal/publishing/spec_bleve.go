var specBleveMetadataKey = []byte("prods-spec-metadata")

const specBleveOwner = "prods-spec-search-root-1\n"

type specBleveMetadata struct {
	Version           string              `json:"version"`
	ProjectionVersion string              `json:"projection_version"`
	Digest            string              `json:"digest"`
	Documents         []specBleveDocument `json:"documents"`
}

// All readers, replacement, and close share this mutex. The cache contains
// only deep-copied frozen publication data verified against stored documents.
type bleveSpecIndex struct {
	mu           sync.Mutex
	root         string
	index        bleve.Index
	owner        *platform.Ownership
	config       Config
	resources    *platform.ResourceGate
	documents    []specBleveDocument
	sourceDigest string
	payloadBytes uint64
	closed       bool
}

func specBleveMapping() *mapping.IndexMappingImpl {
	m := bleve.NewIndexMapping()
	m.DefaultAnalyzer = keyword.Name
	m.StoreDynamic = false
	m.IndexDynamic = true
	m.DocValuesDynamic = false
	m.DefaultMapping.DefaultAnalyzer = keyword.Name
	// Dynamic names are exclusively generated by specBleveIndexFields from
	// full SHA256 namespaces. No user field name or raw document is indexed.
	payload := bleve.NewTextFieldMapping()
	payload.Index = false
	payload.Store = true
	payload.IncludeInAll = false
	payload.IncludeTermVectors = false
	payload.DocValues = false
	m.DefaultMapping.AddFieldMappingsAt("payload", payload)
	return m
}

// Admission estimates reserve 16x canonical JSON plus 8 MiB for payload copies,
// postings, an atomic replacement and query results. This is an overflow-safe
// conservative estimate, not a hard RAM/disk/Scorch background merge limit.
func specBleveEstimate(bytes uint64) (uint64, error) {
	const overhead = 8 << 20
	if bytes > (math.MaxUint64-overhead)/16 {
		return 0, platform.ErrResourceCritical
	}
	return bytes*16 + overhead, nil
}

func (b *bleveSpecIndex) admit(ctx context.Context, size uint64) (*platform.Reservation, error) {
	estimate, err := specBleveEstimate(size)
	if err != nil {
		return nil, err
	}
	r, _, err := b.resources.Admit(ctx, platform.ResourceRequest{Operation: "spec-search-index", Path: b.root, RequiredBytes: estimate, ByteHeadroom: b.config.ByteHeadroom, MinFreePercent: b.config.MinFreePercent, RequiredInodes: 64, InodeHeadroom: b.config.InodeHeadroom})
	return r, err
}

func newBleveSpecIndex(ctx context.Context, root string, config Config) (result *bleveSpecIndex, err error) {
	if root == "" {
		return nil, fmt.Errorf("empty spec index root")
	}
	root, err = filepath.Abs(root)
	if err != nil {
		return nil, err
	}
	b := &bleveSpecIndex{root: root, config: config, resources: config.ResourceGate}
	if b.resources == nil {
		b.resources = platform.NewResourceGate(nil)
	}
	reservation, err := b.admit(ctx, 0)
	if err != nil {
		return nil, err
	}
	defer reservation.Release()
	// Never follow a symlink at either of the private directory boundaries.
	for _, path := range []string{filepath.Dir(root), root} {
		info, statErr := os.Lstat(path)
		if statErr == nil && (!info.IsDir() || info.Mode()&os.ModeSymlink != 0) {
			return nil, fmt.Errorf("unsafe spec index directory: %s", path)
		}
		if statErr != nil && !errors.Is(statErr, os.ErrNotExist) {
			return nil, statErr
		}
		// A caller must give this adapter private directories. Never chmod a
		// shared existing parent such as /tmp merely to open a derived index.
		if runtime.GOOS != "windows" && statErr == nil && info.Mode().Perm()&0o077 != 0 {
			return nil, fmt.Errorf("spec index directory is not private: %s", path)
		}
	}
	if err = os.MkdirAll(filepath.Dir(root), 0o700); err != nil {
		return nil, err
	}
	if err = os.Chmod(filepath.Dir(root), 0o700); err != nil {
		return nil, err
	}
	if err = os.MkdirAll(root, 0o700); err != nil {
		return nil, err
	}
	if err = os.Chmod(root, 0o700); err != nil {
		return nil, err
	}
	lockInfo, lockErr := os.Lstat(filepath.Join(root, "ownership.lock"))
	if lockErr == nil && !lockInfo.Mode().IsRegular() {
		return nil, fmt.Errorf("unsafe spec index ownership file")
	}
	if lockErr != nil && !errors.Is(lockErr, os.ErrNotExist) {
		return nil, lockErr
	}
	ownershipTarget := filepath.Join(root, "ownership")
	targetInfo, targetErr := os.Lstat(ownershipTarget)
	if targetErr == nil && !targetInfo.Mode().IsRegular() {
		return nil, fmt.Errorf("unsafe spec index ownership target")
	}
	if targetErr != nil && !errors.Is(targetErr, os.ErrNotExist) {
		return nil, targetErr
	}
	b.owner, err = platform.AcquireDatabase(ownershipTarget)
	if err != nil {
		return nil, err
	}
	defer func() {
		if err != nil {
			if b.index != nil {
				_ = b.index.Close()
			}
			_ = b.owner.Close()
		}
	}()
	marker := filepath.Join(root, "owner")
	info, statErr := os.Lstat(marker)
	if errors.Is(statErr, os.ErrNotExist) {
		entries, readErr := os.ReadDir(root)
		if readErr != nil {
			return nil, readErr
		}
		for _, entry := range entries {
			if entry.Name() != "ownership.lock" {
				return nil, fmt.Errorf("unowned spec index root: %s", root)
			}
		}
		if err = os.WriteFile(marker, []byte(specBleveOwner), 0o600); err != nil {
			return nil, err
		}
	} else {
		if statErr != nil {
			return nil, statErr
		}
		if !info.Mode().IsRegular() || info.Size() != int64(len(specBleveOwner)) {
			return nil, fmt.Errorf("unsafe spec index owner marker")
		}
		encoded, readErr := os.ReadFile(marker)
		if readErr != nil {
			return nil, readErr
		}
		if string(encoded) != specBleveOwner {
			return nil, fmt.Errorf("unrecognized spec index owner marker")
		}
	}
	child := filepath.Join(root, "index")
	childInfo, statErr := os.Lstat(child)
	if statErr == nil {
		if !childInfo.IsDir() || childInfo.Mode()&os.ModeSymlink != 0 {
			return nil, fmt.Errorf("unsafe spec index child")
		}
		err = filepath.WalkDir(child, func(path string, entry os.DirEntry, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			if !entry.IsDir() && !entry.Type().IsRegular() {
				return fmt.Errorf("unsafe spec index entry: %s", path)
			}
			return nil
		})
		if err == nil {
			b.index, err = bleve.Open(child)
		}
		if err == nil {
			err = b.loadLocked(ctx)
		}
		if err == nil {
			return b, nil
		}
		if specBleveTransientError(err) {
			return nil, err
		}
		if b.index != nil {
			_ = b.index.Close()
			b.index = nil
		}
		// The valid marker and exclusive root lock authorize only a rename of
		// our child. Its files remain available for investigation/recovery.
		if err = b.quarantineLocked(); err != nil {
			return nil, err
		}
	} else if !errors.Is(statErr, os.ErrNotExist) {
		return nil, statErr
	}
	if err = b.createLocked(ctx); err != nil {
		return nil, err
	}
	return b, nil
}

func (b *bleveSpecIndex) quarantineLocked() error {
	child := filepath.Join(b.root, "index")
	if _, err := os.Lstat(child); errors.Is(err, os.ErrNotExist) {
		return nil
	} else if err != nil {
		return err
	}
	return os.Rename(child, filepath.Join(b.root, fmt.Sprintf("quarantine-%d", time.Now().UnixNano())))
}

func (b *bleveSpecIndex) createLocked(ctx context.Context) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	idx, err := bleve.NewUsing(filepath.Join(b.root, "index"), specBleveMapping(), scorch.Name, scorch.Name, nil)
	if err != nil {
		return err
	}
	b.index = idx
	if err = os.Chmod(filepath.Join(b.root, "index"), 0o700); err != nil {
		return err
	}
	docs, digest, err := specBleveDocuments(nil)
	if err != nil {
		return err
	}
	metadata, err := json.Marshal(specBleveMetadata{Version: specBleveVersion, ProjectionVersion: SpecProjectionVersion, Digest: digest, Documents: docs})
	if err != nil {
		return err
	}
	batch := idx.NewBatch()
	batch.SetInternal(specBleveMetadataKey, metadata)
	if err = idx.Batch(batch); err != nil {
		return err
	}
	b.documents = docs
	b.sourceDigest = digest
	b.payloadBytes = uint64(len(metadata))
	return nil
}

func specBleveDecode(encoded []byte, value any) error {
	decoder := json.NewDecoder(bytes.NewReader(encoded))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(value); err != nil {
		return err
	}
	if err := decoder.Decode(new(any)); err != io.EOF {
		return fmt.Errorf("extra spec index payload")
	}
	return nil
}

func (b *bleveSpecIndex) loadLocked(ctx context.Context) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	advanced, err := b.index.Advanced()
	if err != nil {
		return err
	}
	if _, ok := advanced.(*scorch.Scorch); !ok {
		return fmt.Errorf("incompatible spec index type")
	}
	actualMapping, err := json.Marshal(b.index.Mapping())
	if err != nil {
		return err
	}
	expectedMapping, _ := json.Marshal(specBleveMapping())
	if !bytes.Equal(actualMapping, expectedMapping) {
		return fmt.Errorf("incompatible spec index mapping")
	}
	encoded, err := b.index.GetInternal(specBleveMetadataKey)
	if err != nil {
		return err
	}
	reservation, err := b.admit(ctx, uint64(len(encoded)))
	if err != nil {
		return err
	}
	defer reservation.Release()
	var metadata specBleveMetadata
	if err = specBleveDecode(encoded, &metadata); err != nil {
		return err
	}
	if metadata.Version != specBleveVersion || metadata.ProjectionVersion != SpecProjectionVersion {
		return fmt.Errorf("incompatible spec index version")
	}
	docs, digest, err := specBleveValidateDocuments(metadata.Documents)
	if err != nil {
		return err
	}
	if digest != metadata.Digest {
		return fmt.Errorf("invalid spec index digest")
	}
	// Reconstruct from each actual stored document, not metadata copies/count.
	actual, err := b.storedDocumentsLocked(ctx, docs)
	if err != nil {
		return err
	}
	actual, digest, err = specBleveValidateDocuments(actual)
	if err != nil {
		return err
	}
	if digest != metadata.Digest || !reflect.DeepEqual(actual, docs) {
		return fmt.Errorf("spec index documents do not match metadata")
	}
	b.documents = actual
	b.sourceDigest = digest
	b.payloadBytes = uint64(len(encoded))
	return nil
}

func (b *bleveSpecIndex) storedDocumentsLocked(ctx context.Context, expected []specBleveDocument) ([]specBleveDocument, error) {
	count, err := b.index.DocCount()
	if err != nil {
		return nil, err
	}
	if count != uint64(len(expected)) {
		return nil, fmt.Errorf("incomplete spec index document inventory")
	}
	actual := make([]specBleveDocument, 0, len(expected))
	for _, expectedDoc := range expected {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		doc, err := b.index.Document(specBleveProductDocID(expectedDoc.Binding.ProductID))
		if err != nil {
			return nil, err
		}
		if doc == nil {
			return nil, fmt.Errorf("missing spec index document")
		}
		var payload []byte
		fields := 0
		doc.VisitFields(func(field indexapi.Field) {
			if field.Name() == "payload" {
				fields++
				payload = append([]byte(nil), field.Value()...)
			}
		})
		if fields != 1 {
			return nil, fmt.Errorf("invalid spec index stored payload")
		}
		var decoded specBleveDocument
		if err := specBleveDecode(payload, &decoded); err != nil {
			return nil, err
		}
		if decoded.Binding.ProductID != expectedDoc.Binding.ProductID {
			return nil, fmt.Errorf("spec index document identity mismatch")
		}
		actual = append(actual, decoded)
	}
	return actual, nil
}

func (b *bleveSpecIndex) unavailableLocked() {
	b.sourceDigest = ""
	b.documents = nil
	b.payloadBytes = 0
	if b.index != nil {
		_ = b.index.Close()
		b.index = nil
	}
}

func specBleveTransientError(err error) bool {
	return errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded) || errors.Is(err, platform.ErrResourceCritical) || errors.Is(err, platform.ErrResourceUnavailable) || errors.Is(err, os.ErrPermission)
}

func (b *bleveSpecIndex) replace(ctx context.Context, active []ActivePublication) error {
	return b.replaceWithMode(ctx, active, false)
}

// rebuild always performs a real atomic Batch, even for an unchanged source.
func (b *bleveSpecIndex) rebuild(ctx context.Context, active []ActivePublication) error {
	return b.replaceWithMode(ctx, active, true)
}

func (b *bleveSpecIndex) replaceWithMode(ctx context.Context, active []ActivePublication, force bool) (err error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.closed {
		return fmt.Errorf("spec index is closed")
	}
	// Every failed refresh revokes availability, even when admission or payload
	// validation fails before Batch; serving the old digest would hide failure.
	defer func() {
		if err != nil {
			b.unavailableLocked()
		}
	}()
	docs, digest, err := specBleveDocuments(active)
	if err != nil {
		return err
	}
	encoded, err := json.Marshal(specBleveMetadata{Version: specBleveVersion, ProjectionVersion: SpecProjectionVersion, Digest: digest, Documents: docs})
	if err != nil {
		return err
	}
	reservation, err := b.admit(ctx, uint64(len(encoded)))
	if err != nil {
		return err
	}
	defer reservation.Release()
	if b.index == nil {
		if err = b.quarantineLocked(); err != nil {
			return err
		}
		if err = b.createLocked(ctx); err != nil {
			return err
		}
	}
	if !force && digest == b.sourceDigest {
		readErr := b.loadLocked(ctx)
		if readErr == nil && reflect.DeepEqual(b.documents, docs) {
			return nil
		}
		if specBleveTransientError(readErr) {
			return readErr
		}
		// A damaged same-digest index must be rebuilt, never silently skipped.
		b.unavailableLocked()
		if err = b.quarantineLocked(); err != nil {
			return err
		}
		if err = b.createLocked(ctx); err != nil {
			return err
		}
	}
	batch := b.index.NewBatch()
	for _, old := range b.documents {
		batch.Delete(specBleveProductDocID(old.Binding.ProductID))
	}
	for _, doc := range docs {
		if err = ctx.Err(); err != nil {
			return err
		}
		fields, fieldErr := specBleveIndexFields(doc)
		if fieldErr != nil {
			return fieldErr
		}
		if err = batch.Index(specBleveProductDocID(doc.Binding.ProductID), fields); err != nil {
			return err
		}
	}
	batch.SetInternal(specBleveMetadataKey, encoded)
	if err = ctx.Err(); err != nil {
		return err
	}
	if err = b.index.Batch(batch); err != nil {
		return err
	}
	b.documents = docs
	b.sourceDigest = digest
	b.payloadBytes = uint64(len(encoded))
	return b.loadLocked(ctx)
}

func (b *bleveSpecIndex) candidates(ctx context.Context, request SpecSearchRequest) (snapshot SpecCandidateSnapshot, err error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.closed || b.index == nil || b.sourceDigest == "" {
		return snapshot, fmt.Errorf("spec index unavailable")
	}
	if err = ctx.Err(); err != nil {
		return snapshot, err
	}
	for _, predicate := range request.Predicates {
		if err = validateSpecPredicate(predicate); err != nil {
			return snapshot, err
		}
	}
	reservation, err := b.admit(ctx, b.payloadBytes)
	if err != nil {
		return snapshot, err
	}
	defer reservation.Release()
	count, err := b.index.DocCount()
	if err != nil {
		return snapshot, err
	}
	if count != uint64(len(b.documents)) {
		return snapshot, fmt.Errorf("incomplete spec index document inventory")
	}
	plans := specBlevePlans(b.documents, request.Predicates)
	search := bleve.NewSearchRequestOptions(specBleveQuery(plans), len(b.documents), 0, false)
	result, err := b.index.SearchInContext(ctx, search)
	if err != nil {
		return snapshot, err
	}
	if len(result.Status.Errors) > 0 || result.Total != uint64(len(result.Hits)) {
		return snapshot, fmt.Errorf("incomplete spec index hits")
	}
	expected := make(map[string]bool)
	for _, d := range b.documents {
		if specBleveCoarseMatch(d, plans) {
			expected[specBleveProductDocID(d.Binding.ProductID)] = true
		}
	}
	if len(expected) != len(result.Hits) {
		return snapshot, fmt.Errorf("spec index hits disagree with frozen coarse predicate")
	}
	seen := make(map[string]bool, len(result.Hits))
	for _, hit := range result.Hits {
		if !expected[hit.ID] || seen[hit.ID] {
			return snapshot, fmt.Errorf("unexpected or duplicate spec index hit")
		}
		seen[hit.ID] = true
	}
	snapshot = SpecCandidateSnapshot{ProjectionVersion: SpecProjectionVersion, SourceDigest: b.sourceDigest, Inventory: make([]SpecCandidateBinding, 0, len(b.documents)), Candidates: []SpecCandidateBinding{}}
	for _, d := range b.documents {
		binding := d.Binding
		binding.SpecIDs = slices.Clone(binding.SpecIDs)
		snapshot.Inventory = append(snapshot.Inventory, binding)
		if expected[specBleveProductDocID(d.Binding.ProductID)] {
			binding.SpecIDs = slices.Clone(binding.SpecIDs)
			snapshot.Candidates = append(snapshot.Candidates, binding)
		}
	}
	// All bindings and their only nested slice are copied from the frozen cache.
	return snapshot, nil
}

func (b *bleveSpecIndex) digest() string { b.mu.Lock(); defer b.mu.Unlock(); return b.sourceDigest }
func (b *bleveSpecIndex) close() error {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.closed {
		return nil
	}
	b.closed = true
	b.sourceDigest = ""
	b.documents = nil
	var err error
	if b.index != nil {
		err = b.index.Close()
		b.index = nil
	}
	if b.owner != nil {
		err = errors.Join(err, b.owner.Close())
		b.owner = nil
	}
	return err
}
